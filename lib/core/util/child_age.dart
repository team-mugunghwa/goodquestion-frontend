/// 아이 나이 ↔ 출생연도 변환.
///
/// **서버는 나이를 저장하지 않고 출생연도(`birthYear`)만 들고 있습니다.**
/// 나이는 해가 바뀌면 달라지는 값이라 저장할 수 없기 때문입니다. 반면 앱은
/// 아이 등록에서 나이를 받습니다(“7세” 칩) — 보호자가 곧바로 답할 수 있는
/// 값이 나이여서입니다.
///
/// 그래서 두 값 사이를 **모든 화면이 똑같은 식으로** 오가야 합니다. 등록은
/// 나이를 빼서 저장하는데 계정 찾기는 다른 식을 쓰면, 같은 아이인데도 연도가
/// 어긋나 못 찾습니다. 한 줄짜리 계산이지만 흩어져 있으면 그 어긋남을 아무도
/// 못 봅니다 — 그래서 이름을 붙여 한곳에 둡니다.
library;

/// 지금 [age] 살인 아이의 출생연도.
///
/// **"지금" 나이입니다.** 가입할 때 고른 나이를 그대로 넣으면 해가 바뀐 만큼
/// 어긋납니다(2025년에 7세로 등록 → 2018년생, 2026년에는 8세로 물어야 2018이
/// 나옵니다).
int birthYearFromAge(int age, {DateTime? now}) =>
    (now ?? DateTime.now()).year - age;

/// [birthYear] 년에 태어난 아이의 지금 나이. [birthYearFromAge] 의 역입니다.
int ageFromBirthYear(int birthYear, {DateTime? now}) =>
    (now ?? DateTime.now()).year - birthYear;
