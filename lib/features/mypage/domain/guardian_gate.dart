/// 보호자 확인 게이트(모달 5)의 통과 상태.
///
/// ## 왜 상태를 따로 두는가
///
/// 리포트는 아이가 혼자 열면 안 되지만, 보호자가 목록 → 상세 → 목록을 오갈
/// 때마다 확인을 요구하면 못 씁니다. **리포트 영역에 있는 동안만** 열어 둡니다.
///
/// 영역을 벗어나면 `app_router.dart` 가 [reset] 을 부릅니다 — 세션 내내 열어
/// 두면 보호자가 리포트를 보고 태블릿을 아이에게 넘긴 뒤 아이가 비밀번호 없이
/// 리포트를 엽니다.
///
/// ⚠️ 지금은 마이페이지의 호출 지점에서만 **검사**합니다(초기화만 라우터가
/// 합니다). 검사도 `app_router.dart` 의 `redirect` 로 옮기세요 — 화면마다
/// 검사하면 딥링크로 들어오는 경로를 반드시 빠뜨립니다.
/// (`docs/ARCHITECTURE.md` 2장)
class GuardianGate {
  bool _passed = false;

  bool get isPassed => _passed;

  void pass() => _passed = true;

  /// 리포트 영역을 벗어날 때, 그리고 로그아웃·아이 전환처럼 보호자 세션이
  /// 끊기는 시점에 부릅니다.
  void reset() => _passed = false;
}
