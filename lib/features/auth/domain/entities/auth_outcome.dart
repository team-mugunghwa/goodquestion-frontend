/// 로그인이 끝난 뒤 **어디로 가야 하는가.**
///
/// 로그인 성공이 곧 홈 진입은 아닙니다. 이 앱은 계정만으로는 아무것도 할 수
/// 없고 — 아이 프로필이 있어야 발화·단어장·리포트를 귀속시킬 데가 생깁니다.
/// 그래서 "로그인됨"과 "쓸 수 있음"을 구분합니다. (PRD F-01)
enum AuthOutcome {
  /// 신규 가입. 동의부터 받아야 합니다.
  needsConsent,

  /// 로그인은 됐지만 아이 프로필이 없습니다. 프로필 등록으로 보냅니다.
  ///
  /// **여기서 홈으로 빠져나가는 길을 만들지 마세요.** "프로필 없으면 통과
  /// 불가"가 이 화면의 정체성입니다.
  needsChild,

  /// 프로필까지 있는 계정. 홈으로 보냅니다.
  ready,
}
